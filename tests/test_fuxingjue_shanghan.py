"""岐黄选方引擎测试：辅行诀脏腑用药法要 / 伤寒杂病论（含与子午流注、五运六气的联动）。"""

from __future__ import annotations

import pytest

from custom_components.tianyuan_calendar_duo.tianyuan import (
    辅行诀脏腑用药法要类,
    伤寒杂病论类,
)

# ==================== 辅行诀 ====================


def test_获取所有大类法固定顺序() -> None:
    assert 辅行诀脏腑用药法要类.获取所有大类法() == [
        "肝",
        "心",
        "脾",
        "肺",
        "肾",
        "劳",
        "误治",
    ]


@pytest.mark.parametrize("大类", ["肝", "心", "脾", "肺", "肾", "劳", "误治"])
def test_获取大类症状法均非空(大类: str) -> None:
    症状 = 辅行诀脏腑用药法要类.获取大类症状法(大类)
    assert 症状
    assert 症状 == sorted(症状)


def test_获取大类症状法未知大类返回空列表() -> None:
    assert 辅行诀脏腑用药法要类.获取大类症状法("〇") == []


def test_大类症状法互不串味() -> None:
    """脏腑类不应混入劳/误治症状，反之亦然。"""
    肝 = set(辅行诀脏腑用药法要类.获取大类症状法("肝"))
    劳 = set(辅行诀脏腑用药法要类.获取大类症状法("劳"))
    误治 = set(辅行诀脏腑用药法要类.获取大类症状法("误治"))

    assert 肝 and 劳 and 误治
    assert not (肝 & 劳)


def test_辅行诀选方_单症状命中肝实() -> None:
    结果 = 辅行诀脏腑用药法要类.辅行诀选方类("胁下痛")

    assert 结果["state"] == "小泻肝汤"
    assert 结果["summary"].startswith("小泻肝汤 (肝实)")
    属性 = 结果["attributes"]
    assert 属性["证型"] == "肝实"
    assert 属性["脏腑"] == "肝"
    assert 属性["虚实性质"] == "实"
    assert 属性["组成"] == "枳实、芍药、生姜"
    assert 属性["加减参考"]


def test_辅行诀选方_多症状取命中数最高() -> None:
    结果 = 辅行诀脏腑用药法要类.辅行诀选方类(["胁下痛", "气冲心"])
    assert 结果["state"] == "小泻肝汤"


def test_辅行诀选方_未选与未匹配() -> None:
    assert 辅行诀脏腑用药法要类.辅行诀选方类("")["state"] == "未选症状"
    assert 辅行诀脏腑用药法要类.辅行诀选方类(None)["state"] == "未选症状"
    assert 辅行诀脏腑用药法要类.辅行诀选方类("查无此症")["state"] == "未匹配"


def test_辅行诀输出方剂库缺失时返回数据缺失() -> None:
    结果 = 辅行诀脏腑用药法要类._辅行诀输出方剂("肝", "实", "肝实", "不存在的方")
    assert 结果["state"] == "数据缺失"
    assert "不存在的方" in 结果["summary"]


@pytest.mark.parametrize(
    ("经络", "证型", "方名"),
    [
        ("胆经", "实", "小泻肝汤"),
        ("胆经", "平", "小补肝汤"),
        ("心经", "实", "小泻心汤"),
        ("脾经", "虚", "小补脾汤"),
        ("肺经", "实", "小泻肺汤"),
        ("肾经", "虚", "小补肾汤"),
    ],
)
def test_子午流注纳子法辅行诀选方(经络: str, 证型: str, 方名: str) -> None:
    结果 = 辅行诀脏腑用药法要类.子午流注纳子法辅行诀选方(经络, 证型)
    assert 结果.startswith(f"{方名}：")
    assert "、" in 结果  # 组成用顿号连接


def test_五运六气病机辅行诀选方_命中与落空() -> None:
    命中 = 辅行诀脏腑用药法要类.五运六气病机辅行诀选方("风动内扰，肝木不舒")
    assert 命中.startswith("小泻肝汤：")

    落空 = 辅行诀脏腑用药法要类.五运六气病机辅行诀选方("完全不相关的病机")
    assert 落空 == ""


# ==================== 伤寒杂病论 ====================


def test_获取所有六经法() -> None:
    assert 伤寒杂病论类.获取所有六经法() == [
        "太阳",
        "阳明",
        "少阳",
        "太阴",
        "少阴",
        "厥阴",
    ]


@pytest.mark.parametrize("六经", ["太阳", "阳明", "少阳", "太阴", "少阴", "厥阴"])
def test_每经都有证型(六经: str) -> None:
    证型 = 伤寒杂病论类.获取经下所有证型法(六经)
    assert 证型
    assert 证型 == sorted(证型)


def test_获取经下所有证型法_未知六经为空() -> None:
    assert 伤寒杂病论类.获取经下所有证型法("〇") == []


def test_证型与方名双向可查() -> None:
    证型 = 伤寒杂病论类.获取经下所有证型法("太阳")
    assert "太阳-表寒实" in 证型

    assert 伤寒杂病论类.获取证型下所有方名法("太阳-表寒实") == ["麻黄汤"]
    assert 伤寒杂病论类.根据证型查方名法("太阳-表寒实") == "麻黄汤"
    assert 伤寒杂病论类.根据证型查方名法("查无此证") is None


def test_获取方剂数据类() -> None:
    结果 = 伤寒杂病论类.获取方剂数据类("麻黄汤")

    assert 结果["state"] == "麻黄汤"
    assert 结果["summary"] == "麻黄汤：发汗解表，宣肺平喘"
    属性 = 结果["attributes"]
    assert 属性["组成"] == "麻黄、桂枝、杏仁、甘草"
    assert 属性["六经"] == "太阳"
    assert 属性["辨证"] == "太阳-表寒实"
    assert 属性["主治"] and 属性["功用"]


def test_获取方剂数据类_空值且库中缺失() -> None:
    assert 伤寒杂病论类.获取方剂数据类("")["state"] == "未选择"
    缺失 = 伤寒杂病论类.获取方剂数据类("查无此方")
    assert 缺失["state"] == "缺失"
    assert "查无此方" in 缺失["summary"]


@pytest.mark.parametrize(
    ("经络", "证型", "方名"),
    [
        ("胆经", "实", "大柴胡汤"),
        ("胆经", "平", "小柴胡汤"),
        ("肺经", "平", "理中丸"),
    ],
)
def test_子午流注纳子法伤寒选方(经络: str, 证型: str, 方名: str) -> None:
    结果 = 伤寒杂病论类.子午流注纳子法伤寒选方(经络, 证型)
    assert 结果.startswith(f"【{方名}】")


def test_子午流注纳子法伤寒选方_非十二经返回空串() -> None:
    assert 伤寒杂病论类.子午流注纳子法伤寒选方("任脉", "平") == ""


def test_五运六气病机伤寒选方_命中() -> None:
    结果 = 伤寒杂病论类.五运六气病机伤寒选方("风动内扰，肝木不舒")
    assert 结果.startswith("【") and 结果.endswith("】") is False
    assert "、" in 结果
