# ==================== 基础取数 ====================


@pytest.mark.parametrize(
    ("年干", "五运"),
    [("甲", "土运"), ("己", "土运"), ("乙", "金运"), ("丙", "水运"), ("丁", "木运")],
)
def test_获取五运法(年干: str, 五运: str) -> None:
    assert 五运六气类.获取五运法(年干) == 五运


@pytest.mark.parametrize(
    ("年支", "司天", "在泉"),
    [
        ("子", "少阴君火", "阳明燥金"),
        ("午", "少阴君火", "阳明燥金"),
        ("丑", "太阴湿土", "太阳寒水"),
        ("寅", "少阳相火", "厥阴风木"),
        ("卯", "阳明燥金", "少阴君火"),
        ("辰", "太阳寒水", "太阴湿土"),
    ],
)
def test_司天与在泉成对(年支: str, 司天: str, 在泉: str) -> None:
    assert 五运六气类.获取六气法(年支) == 司天
    assert 五运六气类.获取在泉法(年支) == 在泉


def test_未知干支返回占位符() -> None:
    assert 五运六气类.获取五运法("〇") == "未知"
    assert 五运六气类.获取六气法("〇") == "未知"
    assert 五运六气类.获取在泉法("〇") == "未知"
    assert 五运六气类.获取五运偏差法("〇") == ["未知", "未知"]
