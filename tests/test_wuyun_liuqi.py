# ==================== 当前步序 / 全量计算 ====================


def _节气表() -> dict:
    return {
        "大寒": 阳历替身(2026, 1, 20),
        "春分": 阳历替身(2026, 3, 20),
        "小满": 阳历替身(2026, 5, 21),
        "大暑": 阳历替身(2026, 7, 23),
        "秋分": 阳历替身(2026, 9, 23),
        "小雪": 阳历替身(2026, 11, 22),
    }


@pytest.mark.parametrize(
    ("当前", "步序"),
    [
        ((2026, 1, 20), 0),  # 大寒当天即入初之气
        ((2026, 5, 1), 1),  # 春分后、小满前
        ((2026, 5, 21), 2),  # 小满当天即入三之气
        ((2026, 8, 1), 3),
        ((2026, 10, 27), 4),  # 秋分后、小雪前
        ((2026, 11, 22), 5),
    ],
)
def test_获取当前步序法(当前: tuple[int, int, int], 步序: int) -> None:
    农历 = 农历替身(阳历=阳历替身(*当前), 节气表=_节气表())
    assert 五运六气类.获取当前步序法(农历) == 步序


def test_获取当前步序法_节气表缺失时兜底为终之气() -> None:
    农历 = 农历替身(阳历=阳历替身(2026, 1, 1), 节气表={})
    assert 五运六气类.获取当前步序法(农历) == 5


def test_全量计算类返回四段数据并写入缓存() -> None:
    五运六气类._年度缓存.clear()
    农历 = 真农历(datetime(2026, 10, 27, 12, 0))

    结果 = 五运六气类.全量计算类(农历)

    assert set(结果) == {"年五运数据", "年六气数据", "六步运气数据", "年度总览数据"}
    assert 结果["年五运数据"]["state"].startswith("水运")  # 2026 丙午
    assert 结果["年六气数据"]["state"] == "少阴君火司天·阳明燥金在泉"
    assert "state" in 结果["六步运气数据"]
    assert 结果["六步运气数据"]["state"] in {
        "初之气",
        "二之气",
        "三之气",
        "四之气",
        "五之气",
        "终之气",
    }
    assert "丙午" in 五运六气类._年度缓存


def test_全量计算类第二次调用命中年度缓存(monkeypatch: pytest.MonkeyPatch) -> None:
    五运六气类._年度缓存.clear()
    农历 = 真农历(datetime(2026, 10, 27, 12, 0))
    首次 = 五运六气类.全量计算类(农历)

    def _不应被调用(*_args, **_kwargs):
        raise AssertionError("年度总览应命中缓存，不应重算")

    monkeypatch.setattr(五运六气类, "年度总览类", staticmethod(_不应被调用))

    第二次 = 五运六气类.全量计算类(农历)
    assert 第二次["年度总览数据"] == 首次["年度总览数据"]
