# ==================== 纳甲法 ====================


def test_纳甲法_甲日戌时开胆经井穴() -> None:
    """甲日甲戌时是纳甲法的开井时辰：阳日阳时开阳经，取胆经井穴足窍阴。"""
    结果 = 引擎.纳甲法类(农历替身(日干="甲", 日支="戌", 时干="甲", 时支="戌"))

    assert 结果["state"] == "足窍阴"
    属性 = 结果["attributes"]
    assert 属性["穴位"] == "足窍阴"
    assert 属性["输穴"] == "井"
    assert 属性["经络"] == "胆经"
    assert 属性["五行"] == "金"  # 阳经井穴属金
    assert 属性["值日经"] == "胆经"
    assert 属性["三法"] == "阖"  # 戌属阖
    assert "足窍阴" in 属性["摘要"]
    assert 属性["位置"] and 属性["功能"] and 属性["针法"]


def test_纳甲法_甲日亥时顺移到荥穴() -> None:
    """开井之后逐时顺移：井→荥，阳经荥穴属水。"""
    属性 = 引擎.纳甲法类(农历替身(日干="甲", 日支="戌", 时干="乙", 时支="亥"))[
        "attributes"
    ]

    assert 属性["穴位"] == "侠溪"
    assert 属性["输穴"] == "荥"
    assert 属性["经络"] == "胆经"
    assert 属性["五行"] == "水"


def test_纳甲法_阴日阴时开阴经井穴() -> None:
    """乙日乙酉时开肝经井穴大敦，阴经井穴属木。"""
    结果 = 引擎.纳甲法类(农历替身(日干="乙", 日支="丑", 时干="乙", 时支="酉"))

    assert 结果["state"] == "大敦"
    属性 = 结果["attributes"]
    assert 属性["经络"] == "肝经"
    assert 属性["五行"] == "木"
    assert 属性["值日经"] == "肝经"


def test_纳甲法_合日互用取对侧日干的开井() -> None:
    """甲日庚午时本日无穴，借合日（甲己合）己日的开井顺移，取脾经荥穴大都。"""
    属性 = 引擎.纳甲法类(农历替身(日干="甲", 日支="子", 时干="庚", 时支="午"))[
        "attributes"
    ]

    assert 属性["穴位"] == "大都"
    assert 属性["经络"] == "脾经"
    assert 属性["输穴"] == "荥"
    assert 属性["五行"] == "火"  # 阴经荥穴属火
    assert 属性["三法"] == "开"  # 午属开


def test_纳甲法_本日与合日皆闭穴给出提示() -> None:
    结果 = 引擎.纳甲法类(农历替身(日干="甲", 日支="子", 时干="丙", 时支="寅"))

    assert 结果["state"] == "闭穴"
    属性 = 结果["attributes"]
    assert "纳甲开穴" in 属性["详细描述"]
    assert "合日互用" in 属性["详细描述"]
    # 闭穴不返回穴位字段
    assert "穴位" not in 属性


def test_纳甲法_未知日干不会崩溃() -> None:
    结果 = 引擎.纳甲法类(农历替身(日干="〇", 日支="子", 时干="甲", 时支="子"))
    assert 结果["state"] == "闭穴"


