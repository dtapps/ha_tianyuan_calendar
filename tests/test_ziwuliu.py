# ==================== 公共工具 ====================


def test_小时转时支覆盖全部24小时() -> None:
    """零点是子时，一时二时是丑时，二十三点回到子时。"""
    对照 = [引擎.小时转时支(h) for h in range(24)]

    assert len(对照) == 24
    assert 对照[0] == "子"
    assert 对照[1] == 对照[2] == "丑"
    assert 对照[11] == 对照[12] == "午"
    assert 对照[21] == 对照[22] == "亥"
    assert 对照[23] == "子"
    # 十二时辰各出现两次
    assert set(对照) == {
        "子",
        "丑",
        "寅",
        "卯",
        "辰",
        "巳",
        "午",
        "未",
        "申",
        "酉",
        "戌",
        "亥",
    }


def test_穴位详情_已知与未知() -> None:
    已知 = 引擎.穴位详情("少商")
